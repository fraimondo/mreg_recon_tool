function rpath = mreg_recon_tool_gnuparallel_init(data, recon_details, frames_per_job, parallel_jobs)

% Create a job list and a run script to reconstruct using GNU Parallel.
% The jobs are not started: run the generated script (returned in rpath)
% on the machine where the reconstruction should run. Each job calls the
% compiled mreg_recon_tool_recon in 'htcondor' mode.
%
% arguments:
% data = struct with necessary data
% recon_details = struct recon parameters
% frames_per_job = number of timeframes for each job, defaults to 1
% parallel_jobs = number of jobs to run at the same time, defaults to one
%                 per CPU core. Can be overridden when running the script.

if nargin<=2 || isempty(frames_per_job)
    frames_per_job = 1;
else
    frames_per_job = min([frames_per_job,length(recon_details.timeframes)]);
end

if nargin<=3 || isempty(parallel_jobs)
    parallel_jobs_str = '100%'; % GNU Parallel: one job per CPU core
else
    parallel_jobs_str = sprintf('%d', parallel_jobs);
end

if ~exist(recon_details.pname, 'dir')
    mkdir(recon_details.pname);
else
    error('mreg_recon_tool_gnuparallel_init:Dir_exists', 'Directory already exists. Please choose another directory');
end

save([recon_details.pname '/data.mat'], 'data','-v7.3');
save([recon_details.pname, '/recon_details.mat'], 'recon_details','-v7.3');

jobs_fname = fullfile(recon_details.pname, 'gnu_parallel_jobs.txt');
script_fname = fullfile(recon_details.pname, 'run_gnu_parallel.sh');
joblog_fname = fullfile(recon_details.pname, 'gnu_parallel.joblog');

mr_root = getenv('MR_ROOT');
if isempty(mr_root)
    mr_root = 'PATH/TO/MatlabRuntime';
    warning('mreg_recon_tool_gnuparallel_init:mr_root_not_set', 'MR_ROOT is not set. Edit the paths in %s before running.', jobs_fname);
end

mr_recon_path = getenv('MREG_RECON_SA_PATH');
if isempty(mr_recon_path)
    mr_recon_path = 'run_mreg_recon_tool_recon.sh';
end
if ~exist(mr_recon_path, 'file')
    warning('mreg_recon_tool_gnuparallel_init:recon_tool_not_found', 'Compiled mreg_recon_tool_recon not found at "%s". Set MREG_RECON_SA_PATH, or ignore this warning if the jobs will run on another system.', mr_recon_path);
end

% one shell command per line, as expected by GNU Parallel
f_jobs = fopen(jobs_fname, 'w');
current_frame_idx = 1;
n_frames = length(recon_details.timeframes);
job_id = 0;
while current_frame_idx <= n_frames
    t_frames = recon_details.timeframes(current_frame_idx:min(current_frame_idx+frames_per_job-1, n_frames));
    log_base = fullfile(recon_details.pname, sprintf('mreg_recon_batch_%d', job_id));
    fprintf(f_jobs, '%s %s htcondor %s %s %s> %s 2> %s\n', ...
        shell_quote(mr_recon_path), shell_quote(mr_root), ...
        shell_quote(recon_details.pname), shell_quote(recon_details.rawdata_filename), ...
        sprintf('%d ', t_frames), shell_quote([log_base '.out']), shell_quote([log_base '.err']));
    job_id = job_id + 1;
    current_frame_idx = current_frame_idx + frames_per_job;
end
fclose(f_jobs);

script = { ...
    '#!/bin/bash'
    '# This script is auto generated by mreg_recon_tool_gnuparallel_init.m'
    '#'
    '# Usage: run_gnu_parallel.sh [number of parallel jobs]'
    '# The number of jobs defaults to the value chosen when the jobs were created'
    '# (100% means one per CPU core).'
    '# To re-run only the failed jobs, add --resume-failed to the parallel call below.'
    ''
    ['JOBS=${1:-' parallel_jobs_str '}']
    ['parallel --jobs "$JOBS" --joblog ' shell_quote(joblog_fname) ' < ' shell_quote(jobs_fname)]
    };
f_script = fopen(script_fname, 'w');
fprintf(f_script, '%s\n', script{:});
fclose(f_script);
fileattrib(script_fname, '+x');

rpath = script_fname;

end


function s = shell_quote(s)
% quote a string for bash, so paths with spaces or special characters work
s = ['''' strrep(s, '''', '''\''''') ''''];
end
