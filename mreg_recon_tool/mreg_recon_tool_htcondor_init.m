function rpath = mreg_recon_tool_htcondor_init(data, recon_details, frames_per_job)

% Create a job description using HTCondor to submit jobs for reconstruction.
% The jobs are not submitted: run condor_submit_dag on the generated .dag
% file (returned in rpath) from a machine that can submit to HTCondor.
%
% arguments:
% data = struct with necessary data
% recon_details = struct recon parameters
% frames_per_job = number of timeframes for each job, defaults to 1

if nargin<=2 || isempty(frames_per_job)
    frames_per_job = 1;
else
    frames_per_job = min([frames_per_job,length(recon_details.timeframes)]);
end

if ~exist(recon_details.pname, 'dir')
    mkdir(recon_details.pname);
else
    error('mreg_recon_tool_htcondor_init:Dir_exists', 'Directory already exists. Please choose another directory');
end

save([recon_details.pname '/data.mat'], 'data','-v7.3');
save([recon_details.pname, '/recon_details.mat'], 'recon_details','-v7.3');

submit_fname = fullfile(recon_details.pname, 'mreg_recon_batch.submit');
dag_fname = fullfile(recon_details.pname, 'mreg_recon_batch.dag');

mr_root = getenv('MR_ROOT');
if isempty(mr_root)
    mr_root = 'PATH/TO/MatlabRuntime';
    warning('mreg_recon_tool_htcondor_init:mr_root_not_set', 'MR_ROOT is not set. Edit mr_root in %s before submitting.', submit_fname);
end

mr_recon_path = getenv('MREG_RECON_SA_PATH');
if isempty(mr_recon_path)
    mr_recon_path = 'run_mreg_recon_tool_recon.sh';
end
if ~exist(mr_recon_path, 'file')
    warning('mreg_recon_tool_htcondor_init:recon_tool_not_found', 'Compiled mreg_recon_tool_recon not found at "%s". Set MREG_RECON_SA_PATH, or ignore this warning if the jobs will run on another system.', mr_recon_path);
end
initial_dir = fileparts(mr_recon_path);

preamble = [ '# This script is auto generated by mreg_recon_tool_htcondor_init.m\n' ...
    '\n' ...
    '# Environment\n' ...
    'universe = vanilla\n' ...
    'getenv = True\n' ...
    '\n' ...
    '# Resources\n' ...
    'request_cpus = 1\n' ...
    'request_memory = 8G\n' ...
    '\n' ...
    '# Executable\n' ...
    'executable = ' mr_recon_path '\n' ...
    'transfer_executable = False\n' ...
    'initialdir = ' initial_dir '\n' ...
    'mr_root = ' mr_root '\n' ...
    '\n' ...
    '# Arguments\n' ...
    'output_directory = ' recon_details.pname '\n' ...
    'rawdata_filename = ' recon_details.rawdata_filename '\n' ...
    'arguments = $(mr_root) htcondor $(output_directory) $(rawdata_filename) $(frames)\n' ...
    '\n' ...
    '# Logs\n' ...
    'log = $(output_directory)/mreg_recon_batch_$(job_id).log\n' ...
    'output = $(output_directory)/mreg_recon_batch_$(job_id).out\n' ...
    'error = $(output_directory)/mreg_recon_batch_$(job_id).err\n' ...
    '\n' ...
    'queue\n'...
];

% write as plain text so paths containing '%' or '\' are not taken as format
f_submit = fopen(submit_fname, 'w');
fprintf(f_submit, '%s', strrep(preamble, '\n', newline));
fclose(f_submit);

f_dag = fopen(dag_fname, 'w');

current_frame_idx = 1;
n_frames = length(recon_details.timeframes);
job_id = 0;
while current_frame_idx <= n_frames
    t_frames = recon_details.timeframes(current_frame_idx:min(current_frame_idx+frames_per_job-1, n_frames));
    t_frames_str = sprintf('%d ', t_frames);
    fprintf(f_dag, 'JOB job_%d mreg_recon_batch.submit\n', job_id);
    fprintf(f_dag, 'VARS job_%d frames="%s" job_id="%d"\n', job_id, t_frames_str, job_id);
    fprintf(f_dag, '\n');
    job_id = job_id + 1;
    current_frame_idx = current_frame_idx + frames_per_job;
end

fclose(f_dag);

rpath = dag_fname;
